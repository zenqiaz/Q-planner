"""
train_lora_sft.py

LoRA supervised fine-tuning for the MOSAIC-QC method-selection specialists,
over the SFT data already generated by generate_sft.py (jsonl/sft_{cell}.jsonl
+ jsonl/sft_val_{cell}.jsonl). Trains one LoRA adapter per specialist cell:

    organic_general   -- organic DFT (+ CCSD/MP2 organic records)
    organic_TDDFT     -- organic TDDFT
    metal_general     -- TM/heavy DFT + TDDFT + CCSD/MP2 metal records
    (TM_general, heavy_general, highlevel_SP also present as legacy/analysis
     cells -- included for completeness, not part of the 3-cell architecture)

Base model per the design doc (discussion_draft_0622.md, Section 5):
"Llama-3.1-8B or equivalent available on NII H200 cluster." Any HF causal LM
with a working chat template works (Llama-3.1-Instruct, Qwen2.5-Instruct,
Mistral-Instruct, ...) -- the masking logic below reads the template rather
than assuming a specific model's special tokens.

Training objective: standard causal LM loss, masked to the assistant's JSON
completion only (system+user tokens contribute zero loss). This is done by
rendering the prompt (everything up to and including the assistant header)
and the full conversation through the SAME tokenizer call, then diffing
token-index lengths -- verified to give an exact token-level prefix match
across chat-template models (see commit notes / session log), so it doesn't
hardcode any model's special-token spelling.

Evaluation (post-training, per dataset_manual.md's acceptance criterion):
generates completions for every validation example and reports the
functional+basis exact-match rate -- the checklist's target is >=80%.
Cells with an empty val file skip evaluation with a warning rather than
failing (none of the 3 main cells are empty as of this corpus snapshot,
after fixing tmQM's upload_id clustering -- see merge_methods.py).

First-step scope: --cell phase1 trains only organic_general + metal_general
(organic_TDDFT deferred). Use --cell all/main once phase1 results are in.

Requirements (see requirements.txt next to this file):
    torch (install the CUDA build matching your cluster first, see
           https://pytorch.org/get-started/locally/)
    transformers>=4.44
    peft>=0.12
    datasets>=2.19
    accelerate>=0.33
    bitsandbytes>=0.43   (only needed for --load-in-4bit / QLoRA)

Usage
-----
  # Recommended first step: organic_general + metal_general only
  # (bf16, no quantization -- fine on an H200):
  python train_lora_sft.py --cell phase1

  # Single cell:
  python train_lora_sft.py --cell organic_general

  # All cells including organic_TDDFT and the legacy/analysis ones:
  python train_lora_sft.py --cell all

  # QLoRA (4-bit) if running on a smaller/shared GPU:
  python train_lora_sft.py --cell metal_general --load-in-4bit

  # Different base model:
  python train_lora_sft.py --cell organic_general \
      --base-model Qwen/Qwen2.5-7B-Instruct

Output: LoRA adapter weights + training_config.json + eval_report.json under
  lora_output/{cell}/
"""

